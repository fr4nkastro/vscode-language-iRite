/** Pure Markdown/SVG documentation generator. No `vscode` imports; deterministic given `now`. */
import * as path from "node:path";
import type { IriteProjectModel, IriteRoutine } from "../irite";
import type { RevModel } from "../rev";
import { buildErd } from "../erd/erdModel";
import { erdToMermaid } from "../erd/erdMermaid";
import { buildSfc } from "../sfc/sfcModel";
import type { SfcOptions } from "../sfc/sfcModel";
import { sfcToMermaid } from "../sfc/sfcMermaid";
import { buildCallGraph } from "../callmap/callGraph";
import { callMapToMermaid } from "../callmap/callMermaid";
import { callViews } from "../callmap/callViews";
import { buildScreenView } from "../preview/screenModel";
import type { WidgetView } from "../preview/screenModel";
import { CANVAS_HEIGHT, CANVAS_WIDTH } from "../preview/screenHtml";

export const GENERATED_MARKER = '<!-- Generated by iRite extension: do not edit; regenerate with "iRite: Generate Project Docs" -->';
export const OUTPUT_DIR = "docs/generated";

export interface DocsInput {
	project: IriteProjectModel;
	rev?: RevModel;
	/** Absolute folder of `main.src`. */
	projectDir: string;
	version: string;
	now: Date;
	sfcOptions?: SfcOptions;
	builtinImageUri?: (id: string, panel: "7" | "12") => string | undefined;
}

export interface DocsFile {
	/** Project-relative, forward slashes. */
	relPath: string;
	content: string;
}

export interface DocsDiagnostic {
	source: "project" | "rev" | "erd" | "sfc" | "callmap";
	message: string;
}

export interface DocsOutput {
	files: DocsFile[];
	diagnostics: DocsDiagnostic[];
}

/** True when the target may be written: it does not exist, or it carries the generated marker. */
export function shouldWrite(existingContent: string | undefined): boolean {
	if (existingContent === undefined) {
		return true;
	}
	const first = existingContent.replace(/^\uFEFF/, "").split(/\r?\n/, 1)[0].trim();
	return first === GENERATED_MARKER;
}

/** Escapes a Markdown table cell: `|`, newlines and angle brackets. */
export function cell(s: string | number | undefined): string {
	if (s === undefined || s === "") {
		return "";
	}
	return String(s)
		.replace(/\r\n|\r|\n/g, " ")
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/\|/g, "\\|");
}

const codeCell = (s: string): string => "`" + cell(s).replace(/`/g, "'") + "`";

function xml(s: string): string {
	return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

export function generateDocs(input: DocsInput): DocsOutput {
	const { project, rev, projectDir, version, now } = input;
	const outAbs = path.join(projectDir, ...OUTPUT_DIR.split("/"));
	const link = (file: string, line?: number): string => {
		const rel = path.relative(outAbs, file).split(path.sep).join("/").replace(/ /g, "%20");
		return line !== undefined ? `${rel}#L${line}` : rel;
	};
	const label = (file: string): string => {
		const rel = path.relative(projectDir, file).split(path.sep).join("/");
		return rel.startsWith("..") ? file.split(path.sep).join("/") : rel;
	};
	const ref = (file: string, line: number): string => `[${cell(label(file))}:${line}](${link(file, line)})`;
	const withMarker = (body: string): string => GENERATED_MARKER + "\n" + body.replace(/\s+$/, "") + "\n";

	const diagnostics: DocsDiagnostic[] = [];
	for (const d of project.diagnostics) {
		diagnostics.push({ source: "project", message: `${label(d.file)}:${d.line}: ${d.message}` });
	}
	for (const d of rev?.diagnostics ?? []) {
		diagnostics.push({ source: "rev", message: `line ${d.line}: ${d.message}` });
	}
	const erd = buildErd(project, rev);
	const sfc = buildSfc(project, input.sfcOptions ?? {});
	const screensView = rev ? buildScreenView(rev, project) : { screens: [], diagnostics: [] };
	erd.diagnostics.forEach((d) => diagnostics.push({ source: "erd", message: d.message }));
	sfc.diagnostics.forEach((d) => diagnostics.push({ source: "sfc", message: d.message }));
	const callGraph = buildCallGraph(project, projectDir);
	callGraph.diagnostics.forEach((d) => diagnostics.push({ source: "callmap", message: d }));

	const base = OUTPUT_DIR;
	const files: DocsFile[] = [];
	const projectName = path.basename(projectDir);
	const handlers = project.routines.filter((r) => r.kind === "handler");
	const subs = project.routines.filter((r) => r.kind !== "handler");

	// ---- index.md
	{
		const l = [`# ${cell(projectName)} — project documentation`, "", `Generated ${now.toISOString()} by iRite extension v${cell(version)}.`, ""];
		l.push("## Summary", "", "| Item | Count |", "| --- | --- |");
		l.push(`| Source files | ${project.files.length} |`);
		l.push(`| Databases | ${project.databases.length} |`);
		l.push(`| Enums | ${project.enums.length} |`);
		l.push(`| Procedures / functions | ${subs.length} |`);
		l.push(`| Handlers | ${handlers.length} |`);
		l.push(`| Widgets (.rev) | ${rev ? rev.widgets.length : 0} |`);
		l.push(`| Screens (.rev) | ${screensView.screens.length} |`, "");
		l.push("## Pages", "", "- [Database diagram (ERD)](erd.md)", "- [Sequence diagram (SFC)](sfc.md)", "- [Screens](screens.md)", "- [Routines](routines.md)", "- [Call map (modules)](callmap.md)", "");
		l.push("## Files (include order)", "");
		project.files.forEach((f, i) => l.push(`${i + 1}. [${cell(label(f))}](${link(f)})`));
		if (diagnostics.length > 0) {
			l.push("", "## Diagnostics", "");
			diagnostics.forEach((d) => l.push(`- (${d.source}) ${cell(d.message)}`));
		}
		files.push({ relPath: `${base}/index.md`, content: withMarker(l.join("\n")) });
	}

	// ---- erd.md
	{
		const l = ["# Database diagram (ERD)", ""];
		if (erd.tables.length === 0) {
			l.push("No databases found.", "");
		} else {
			l.push("```mermaid", erdToMermaid(erd).trimEnd(), "```", "");
			l.push("> Relations are **inferred** from field naming heuristics; neither the source nor the `.rev` declares foreign keys.", "");
			if (erd.relations.length > 0) {
				l.push("| From | To |", "| --- | --- |");
				erd.relations.forEach((r) => l.push(`| ${cell(r.from.table)}.${cell(r.from.field)} | ${cell(r.to.table)}.${cell(r.to.field)} |`));
				l.push("");
			}
			for (const t of erd.tables) {
				l.push(`## ${cell(t.name)}`, "");
				const meta = [`origin: ${t.origin}`];
				if (t.typeName) {
					meta.push(`type: ${cell(t.typeName)}`);
				}
				if (t.maxRecords !== undefined) {
					meta.push(`max records: ${t.maxRecords}`);
				}
				if (t.source) {
					meta.push(`declared at ${ref(t.source.file, t.source.line)}`);
				}
				l.push(meta.join(" · "), "", "| Field | Type | Size |", "| --- | --- | --- |");
				t.fields.forEach((f) => l.push(`| ${cell(f.name)} | ${cell(f.type)} | ${cell(f.size)} |`));
				l.push("");
			}
		}
		l.push("## Diagnostics", "");
		if (erd.diagnostics.length === 0) {
			l.push("None.");
		} else {
			erd.diagnostics.forEach((d) => l.push(`- ${d.severity}: ${cell(d.message)}`));
		}
		files.push({ relPath: `${base}/erd.md`, content: withMarker(l.join("\n")) });
	}

	// ---- sfc.md
	{
		const l = ["# Sequence diagram (SFC)", ""];
		if (sfc.steps.length === 0) {
			l.push("No STATES/TRANSITIONS state machine found.", "");
		} else {
			l.push("```mermaid", sfcToMermaid(sfc).trimEnd(), "```", "");
			l.push("## Steps", "", "| Step | Entry routine | Location | Initial |", "| --- | --- | --- | --- |");
			for (const s of sfc.steps) {
				l.push(`| ${cell(s.name)} | ${cell(s.entryRoutine)} | ${s.source ? ref(s.source.file, s.source.line) : ""} | ${s.initial ? "yes" : ""} |`);
			}
			l.push("", "## Transitions", "", "| Transition | From -> To | Emitted by (file:line, condition) |", "| --- | --- | --- |");
			for (const t of sfc.transitions) {
				const from = t.sources.length > 0 ? t.sources.join(", ") + (t.anyStep ? ", any step" : "") : t.anyStep ? "any step" : "—";
				const emitted = t.emitters.map((e) => ref(e.file, e.line) + (e.conditions.length > 0 ? ` ${codeCell(e.conditions.join(" and "))}` : "")).join("<br>");
				l.push(`| ${cell(t.name)} | ${cell(from)} -> ${cell(t.target ?? "?")} | ${emitted} |`);
			}
			l.push("");
		}
		l.push("## Diagnostics", "");
		if (sfc.diagnostics.length === 0) {
			l.push("None.");
		} else {
			sfc.diagnostics.forEach((d) => l.push(`- ${d.severity}: ${cell(d.message)}${d.file && d.line ? ` (${ref(d.file, d.line)})` : ""}`));
		}
		files.push({ relPath: `${base}/sfc.md`, content: withMarker(l.join("\n")) });
	}

	// ---- screens.md + SVGs
	{
		const l = ["# Screens", ""];
		const svgs: DocsFile[] = [];
		if (!rev) {
			l.push("No `.rev` file found next to `main.src`: screens cannot be documented.", "");
		} else if (screensView.screens.length === 0) {
			l.push("The `.rev` defines no screens.", "");
		} else {
			l.push("Screen names come from code, not from the `.rev`; screens are identified by number. Wireframes are approximate (usable area 800x388).", "");
		}
		for (const sc of screensView.screens) {
			l.push(`## Screen ${sc.number}`, "", `![Screen ${sc.number} wireframe](screens/screen-${sc.number}.svg)`, "");
			l.push("| Id | Type | Alias | Text | x,y,w,h | Code references |", "| --- | --- | --- | --- | --- | --- |");
			for (const w of sc.widgets) {
				const geo = [w.x, w.y, w.width, w.height].map((n) => (n === undefined ? "?" : String(n))).join(",");
				const refs = w.references.map((r) => `${ref(r.file, r.line)} ${codeCell(r.callee)}`).join("<br>");
				l.push(`| ${w.id} | ${cell(w.typeName)} (${w.type}) | ${cell(w.alias)} | ${cell(w.text)} | ${geo} | ${refs} |`);
			}
			l.push("");
			svgs.push({ relPath: `${base}/screens/screen-${sc.number}.svg`, content: renderSvg(sc.number, sc.widgets, input.builtinImageUri) });
		}
		files.push({ relPath: `${base}/screens.md`, content: withMarker(l.join("\n")) }, ...svgs);
	}

	// ---- callmap.md
	{
		const l = ["# Call map (modules)", ""];
		if (callGraph.routines.length === 0) {
			l.push("No routines found.", "");
		} else {
			const view = callViews.moduleView(callGraph, "file");
			l.push("Each arrow is \"caller module calls callee module\", labelled with the number of calls. Calls to built-in API names (not declared in the project) are left out. Open **iRite: Show Call Map** for the interactive version, which also drills into routines.", "");
			l.push("```mermaid", callMapToMermaid(callGraph).trimEnd(), "```", "");
			if (callGraph.hiddenFiles > 0) {
				l.push(`${callGraph.hiddenFiles} file(s) without routines (\`main.src\`, declaration-only files) are not drawn.`, "");
			}
			l.push("## Calls between modules", "");
			if (view.edges.length === 0) {
				l.push("No calls between modules.", "");
			} else {
				l.push("| Caller module | Callee module | Calls | Call sites |", "| --- | --- | --- | --- |");
				for (const e of view.edges) {
					const sites = e.sites.map((i) => {
						const s = callGraph.sites[i];
						const f = callGraph.files[callGraph.routines[s.from].file].file;
						return `${codeCell(callGraph.routines[s.from].name)} -> ${codeCell(callGraph.routines[s.to].name)} ${ref(f, s.line)}`;
					});
					l.push(`| ${cell(e.from)} | ${cell(e.to)} | ${e.count} | ${sites.join("<br>")} |`);
				}
				l.push("");
			}
		}
		files.push({ relPath: `${base}/callmap.md`, content: withMarker(l.join("\n")) });
	}

	// ---- routines.md
	{
		const l = ["# Routines", "", "See the [module call map](callmap.md) for how these routines call each other.", ""];
		const byFile = new Map<string, IriteRoutine[]>();
		for (const r of project.routines) {
			byFile.set(r.file, [...(byFile.get(r.file) ?? []), r]);
		}
		if (byFile.size === 0) {
			l.push("No routines found.");
		}
		for (const f of project.files) {
			const list = byFile.get(f);
			if (!list) {
				continue;
			}
			l.push(`## ${cell(label(f))}`, "", "| Kind | Signature | Location |", "| --- | --- | --- |");
			for (const r of list) {
				l.push(`| ${r.kind}${r.forward ? " (forward)" : ""} | ${codeCell(signature(r))} | [line ${r.line}](${link(r.file, r.line)}) |`);
			}
			l.push("");
		}
		files.push({ relPath: `${base}/routines.md`, content: withMarker(l.join("\n")) });
	}

	return { files, diagnostics };
}

function signature(r: IriteRoutine): string {
	if (r.kind === "handler") {
		return `handler ${r.name}`;
	}
	const params = r.params.map((p) => `${p.name}: ${p.type}`).join("; ");
	return `${r.kind} ${r.name}${r.params.length > 0 ? `(${params})` : ""}${r.returnType ? `: ${r.returnType}` : ""}`;
}

const SAFE_COLOR = /^(#[0-9A-Fa-f]{3,8}|[A-Za-z]{3,20})$/;
const color = (c: string | undefined, fallback: string): string => (c && SAFE_COLOR.test(c) ? c : fallback);

function renderSvg(screen: number, widgets: WidgetView[], builtinImageUri?: DocsInput["builtinImageUri"]): string {
	const out: string[] = [GENERATED_MARKER];
	out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS_WIDTH} ${CANVAS_HEIGHT}" width="${CANVAS_WIDTH}" height="${CANVAS_HEIGHT}" font-family="sans-serif">`);
	out.push(`<title>${xml(`Screen ${screen}`)}</title>`);
	out.push(`<rect x="0" y="0" width="${CANVAS_WIDTH}" height="${CANVAS_HEIGHT}" fill="#ffffff" stroke="#888888"/>`);
	for (const w of widgets) {
		const x = w.x ?? 0;
		const y = w.y ?? 0;
		const head = `<g class="widget" data-id="${w.id}" data-type="${xml(w.typeName)}">`;
		if (w.typeName === "line") {
			const horizontal = (w.width ?? 0) >= (w.height ?? 0);
			const len = w.width ?? 0;
			const th = Math.max(1, w.height ?? 1);
			out.push(`${head}<rect x="${x}" y="${y}" width="${horizontal ? len : th}" height="${horizontal ? th : len}" fill="${xml(color(w.color, "#444444"))}"/></g>`);
			continue;
		}
		const width = w.width ?? 60;
		const height = w.height ?? 24;
		const uri = w.typeName === "image" && w.image?.startsWith("local://") ? builtinImageUri?.(w.image.slice(8), "7") : undefined;
		if (uri && /^file:\/\/\//.test(uri)) {
			out.push(`${head}<image href="${xml(uri)}" x="${x}" y="${y}" width="${width}" height="${height}" preserveAspectRatio="none"/></g>`);
			continue;
		}
		const fill = w.typeName === "image" ? "#e8e8e8" : color(w.background, "none");
		const text = w.typeName === "image" ? `[image: ${w.image ?? ""}]` : (w.text ?? w.alias ?? w.typeName);
		const size = Math.max(8, Math.min(w.fontSize ?? 12, Math.max(8, height - 4)));
		out.push(
			`${head}<rect x="${x}" y="${y}" width="${width}" height="${height}" fill="${xml(fill)}" stroke="${xml(color(w.color, "#666666"))}" stroke-dasharray="${w.typeName === "image" ? "4 2" : "0"}"/>` +
				`<text x="${x + 3}" y="${y + Math.min(height - 3, size + 2)}" font-size="${size}">${xml(text)}</text></g>`,
		);
	}
	out.push("</svg>");
	return out.join("\n") + "\n";
}
