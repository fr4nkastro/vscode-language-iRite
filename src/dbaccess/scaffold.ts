/** Stub generation and (pure) scaffold planning. No `vscode` imports, no file IO. */
import * as path from 'node:path';
import type { DbAccessReport } from './check';
import { PENDING_MARKER, type DbAccessOptions, type ExpectedRoutine } from './convention';

export interface ScaffoldEdits {
	/** Table module (created or appended). Empty when nothing needs adding. */
	files: { path: string; text: string }[];
	/** `main.src` with the new include. Undefined when no change is needed. */
	mainSrc?: { path: string; text: string };
	/** Names of the stubs added. */
	added: string[];
}

/** One compilable stub. Fails loudly (`SysInvalidRequest`) until implemented, never pretends to succeed. */
export function renderStub(e: ExpectedRoutine): string {
	return [
		`-- irite-db: ${e.table}${e.field !== undefined ? ` / ${e.field}` : ''} / ${e.group}`,
		`-- ${e.description}`,
		e.signature,
		'begin',
		`    ${PENDING_MARKER}`,
		'    return SysInvalidRequest;',
		'end;',
		'',
	].join('\n');
}

const safeFileName = (table: string): string => table.replace(/[^A-Za-z0-9_]/g, '_');

/** Project-relative path of a table's module, with the given separator. */
export function modulePath(table: string, folder: string, sep: '/' | '\\'): string {
	const parts = folder.split(/[\\/]+/).filter(p => p !== '' && p !== '.');
	return [...parts, `${safeFileName(table)}.iri`].join(sep);
}

const detectEol = (text: string): string => (text.includes('\r\n') ? '\r\n' : '\n');
const includeRe = (p: string): RegExp => new RegExp(`^\\s*#include\\s+${p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`, 'i');

/**
 * Adds `#include <newRel>` right after the include of `afterRel` (the file that declares the
 * table), else after the last include. Idempotent; commented includes do not count.
 */
export function planIncludeInsertion(mainSrcText: string, afterRel: string, newRel: string): { text: string; changed: boolean } {
	const eol = detectEol(mainSrcText);
	const lines = mainSrcText.split(/\r?\n/);
	if (lines.some(l => includeRe(newRel).test(l))) {
		return { text: mainSrcText, changed: false };
	}
	let at = lines.findIndex(l => includeRe(afterRel).test(l));
	if (at < 0) {
		for (let i = 0; i < lines.length; i++) {
			if (/^\s*#include\s/i.test(lines[i])) {
				at = i;
			}
		}
	}
	if (at < 0) {
		at = lines.findIndex(l => /^\s*program\b/i.test(l));
	}
	lines.splice(at + 1, 0, `#include ${newRel}`);
	return { text: lines.join(eol), changed: true };
}

export interface ScaffoldInput {
	report: DbAccessReport;
	table: string;
	mainSrcPath: string;
	readText: (file: string) => string | undefined;
	options: DbAccessOptions;
}

/**
 * Plans the edits that scaffold the MISSING routines of one table. Pending stubs are left alone,
 * routines found by name in the target module are never duplicated, existing text is never rewritten
 * (new stubs are appended).
 */
export function applyScaffold(input: ScaffoldInput): ScaffoldEdits {
	const t = input.report.tables.find(x => x.table.toLowerCase() === input.table.toLowerCase());
	const none: ScaffoldEdits = { files: [], added: [] };
	if (!t) {
		return none;
	}
	const root = path.dirname(input.mainSrcPath);
	const folder = input.options.moduleFolder;
	const target = path.join(root, ...modulePath(t.table, folder, '/').split('/'));
	const existing = input.readText(target);
	const lower = (existing ?? '').toLowerCase();
	const todo = t.items.filter(
		i => i.status === 'missing' && !new RegExp(`\\b(function|procedure)\\s+${i.expected.name.toLowerCase()}\\b`).test(lower),
	);
	if (todo.length === 0) {
		return none;
	}
	const eol = existing !== undefined ? detectEol(existing) : '\n';
	const body = todo.map(i => renderStub(i.expected)).join('\n').replace(/\n/g, eol);
	let text: string;
	if (existing === undefined) {
		text = [
			`-- Generated by "iRite: Scaffold DB Access Routines" for table ${t.table}.`,
			`-- Every stub fails with SysInvalidRequest until implemented: implement it, then delete its ${PENDING_MARKER} line.`,
			'',
			'',
		].join('\n').replace(/\n/g, eol) + body;
	} else {
		text = existing + (existing === '' || /\r?\n$/.test(existing) ? '' : eol) + eol + body;
	}
	const edits: ScaffoldEdits = { files: [{ path: target, text }], added: todo.map(i => i.expected.name) };
	const mainText = input.readText(input.mainSrcPath);
	if (mainText !== undefined) {
		const declRel = path.relative(root, t.file).split(path.sep).join('\\');
		const plan = planIncludeInsertion(mainText, declRel, modulePath(t.table, folder, '\\'));
		if (plan.changed) {
			edits.mainSrc = { path: input.mainSrcPath, text: plan.text };
		}
	}
	return edits;
}
