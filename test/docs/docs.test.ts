import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { loadIriteProject } from "../../src/irite";
import { parseRev } from "../../src/rev";
import { generateDocs, shouldWrite, GENERATED_MARKER } from "../../src/docs/generateDocs";

const projectDir = resolve(__dirname, "../fixtures/irite");
const mainSrc = join(projectDir, "main.src");
const project = loadIriteProject(mainSrc, (p) => {
	try {
		return readFileSync(p, "utf8");
	} catch {
		return undefined;
	}
});
const rev = parseRev(readFileSync(join(__dirname, "../fixtures/rev/sample.rev"), "utf8"));
const now = new Date("2026-01-02T03:04:05.000Z");
const run = (r = rev) => generateDocs({ project, rev: r, projectDir, version: "9.9.9", now });
const get = (out: ReturnType<typeof run>, p: string) => out.files.find((f) => f.relPath === p)!.content;

describe("generateDocs", () => {
	const out = run();
	it("emits the expected file set under docs/generated", () => {
		const paths = out.files.map((f) => f.relPath);
		for (const p of ["docs/generated/index.md", "docs/generated/erd.md", "docs/generated/sfc.md", "docs/generated/screens.md", "docs/generated/routines.md"]) {
			expect(paths).toContain(p);
		}
		const screens = [...new Set(rev.widgets.map((w) => w.screen).filter((s) => s !== undefined))] as number[];
		expect(screens.length).toBeGreaterThan(0);
		for (const n of screens) {
			expect(paths).toContain(`docs/generated/screens/screen-${n}.svg`);
		}
		expect(new Set(paths).size).toBe(paths.length);
	});
	it("starts every file with the marker", () => {
		for (const f of out.files) {
			expect(f.content.startsWith(GENERATED_MARKER + "\n")).toBe(true);
		}
		expect(GENERATED_MARKER).toBe('<!-- Generated by iRite extension: do not edit; regenerate with "iRite: Generate Project Docs" -->');
	});
	it("is deterministic for a fixed now and carries timestamp and version", () => {
		expect(run()).toEqual(out);
		const idx = get(out, "docs/generated/index.md");
		expect(idx).toContain("2026-01-02T03:04:05.000Z");
		expect(idx).toContain("9.9.9");
		expect(idx).toContain("(erd.md)");
		expect(idx).toContain("(sfc.md)");
		expect(idx).toContain("(screens.md)");
		expect(idx).toContain("(routines.md)");
	});
	it("uses relative forward-slash links with #L anchors", () => {
		const routines = get(out, "docs/generated/routines.md");
		expect(routines).toMatch(/\]\(\.\.\/\.\.\/[^)\s\\]+#L\d+\)/);
		expect(routines).not.toContain("\\");
		const idx = get(out, "docs/generated/index.md");
		expect(idx).toContain("(../../main.src)");
	});
	it("renders the ERD with mermaid, relation note and field table", () => {
		const erd = get(out, "docs/generated/erd.md");
		expect(erd).toContain("```mermaid\nerDiagram");
		expect(erd.toLowerCase()).toContain("inferred");
		expect(erd).toContain("| Field | Type | Size |");
	});
	it("renders the SFC section with the transitions table header", () => {
		const sfc = get(out, "docs/generated/sfc.md");
		expect(sfc).toContain("| Transition | From -> To | Emitted by (file:line, condition) |");
	});
	it("escapes | and newlines in table cells", () => {
		const r = parseRev(readFileSync(join(__dirname, "../fixtures/rev/sample.rev"), "utf8"));
		const w = r.widgets.find((x) => x.typeName === "label" && x.screen !== undefined)!;
		w.text = "a|b\nc";
		w.alias = "x|y";
		const screens = get(run(r), "docs/generated/screens.md");
		expect(screens).toContain("a\\|b c");
		expect(screens).toContain("x\\|y");
		expect(screens).not.toMatch(/a\|b/);
	});
	it("SVG wireframe has one element per widget, escapes text, 800x388 viewBox", () => {
		const r = parseRev(readFileSync(join(__dirname, "../fixtures/rev/sample.rev"), "utf8"));
		const w = r.widgets.find((x) => x.typeName === "label" && x.screen !== undefined)!;
		w.text = `<b>&"x"</b>`;
		const o = run(r);
		const svg = get(o, `docs/generated/screens/screen-${w.screen}.svg`);
		const count = r.widgets.filter((x) => x.screen === w.screen).length;
		expect(svg.match(/<g class="widget"/g)!.length).toBe(count);
		expect(svg).toContain('viewBox="0 0 800 388"');
		expect(svg).toContain("&lt;b&gt;&amp;&quot;x&quot;&lt;/b&gt;");
		expect(svg).not.toContain("<b>");
	});
	it("emits docs even without a .rev", () => {
		const o = generateDocs({ project, projectDir, version: "1", now });
		expect(o.files.map((f) => f.relPath)).toContain("docs/generated/screens.md");
		expect(o.files.some((f) => f.relPath.endsWith(".svg"))).toBe(false);
	});
});

describe("shouldWrite", () => {
	it("writes new files and marked files, skips hand-written ones", () => {
		expect(shouldWrite(undefined)).toBe(true);
		expect(shouldWrite(GENERATED_MARKER + "\n# x")).toBe(true);
		expect(shouldWrite("\uFEFF" + GENERATED_MARKER + "\r\n# x")).toBe(true);
		expect(shouldWrite("# my notes")).toBe(false);
		expect(shouldWrite("")).toBe(false);
	});
});
